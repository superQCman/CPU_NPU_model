from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any

try:
    from .machine_topology import detect_machine_topology, write_machine_config
except ImportError:
    from machine_topology import detect_machine_topology, write_machine_config


SCRIPT_DIR = Path(__file__).resolve().parent
PROJECT_ROOT = SCRIPT_DIR.parent
DEFAULT_TEMPLATE = SCRIPT_DIR / "hw_config" / "kunpeng920_single_numa.yaml"


def _load_yaml_like(path: Path) -> dict[str, Any]:
    try:
        import yaml  # type: ignore
    except ImportError:
        return json.loads(path.read_text(encoding="utf-8"))
    data = yaml.safe_load(path.read_text(encoding="utf-8"))
    return data if isinstance(data, dict) else {}


def _dump_yaml_like(path: Path, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        import yaml  # type: ignore
    except ImportError:
        path.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        return
    path.write_text(yaml.safe_dump(payload, sort_keys=False, allow_unicode=True), encoding="utf-8")


def _slug(text: str) -> str:
    clean = re.sub(r"[^A-Za-z0-9]+", "_", text.strip()).strip("_").lower()
    return clean or "detected_cpu"


def _node_meta(topology: dict[str, Any], node_index: int) -> dict[str, Any]:
    for item in topology.get("numa_nodes", []):
        if int(item.get("node", -1)) == int(node_index):
            return dict(item)
    return {"node": int(node_index), "cpu_list": "", "cpu_count": topology.get("online_cpu_count", 1), "mem_mb": None}


def build_hw_config_from_template(
    *,
    template_path: Path,
    profile_name: str | None,
    numa_node: int,
) -> tuple[dict[str, Any], dict[str, Any]]:
    topology = detect_machine_topology()
    payload = _load_yaml_like(template_path)
    model_name = str(topology.get("model_name") or topology.get("vendor_id") or "detected_cpu")
    resolved_profile = profile_name or f"{_slug(model_name)}_numa{int(numa_node)}"
    node = _node_meta(topology, numa_node)

    payload["profile_name"] = resolved_profile
    payload["source_config"] = str(template_path)
    notes = list(payload.get("notes", [])) if isinstance(payload.get("notes"), list) else []
    notes.append(
        "Auto-generated by calibrator/generate_machine_hw_config.py from local topology and a calibration template; "
        "rerun hardware_calibration for production-grade numeric bandwidth/latency fields."
    )
    payload["notes"] = notes

    scope = dict(payload.get("scope", {}))
    scope.update(
        {
            "execution_scope": "single_numa",
            "locality": "numa_local",
            "numa_node_index": int(numa_node),
            "numa_cpu_list": str(node.get("cpu_list", "")),
            "numa_mem_mb": node.get("mem_mb"),
        }
    )
    payload["scope"] = scope

    core = dict(payload.get("core", {}))
    cpu_count = int(node.get("cpu_count") or topology.get("online_cpu_count") or 1)
    core.update(
        {
            "architecture": topology.get("architecture") or core.get("architecture"),
            "vendor": topology.get("vendor_id") or core.get("vendor"),
            "model_name": model_name,
            "sockets": topology.get("socket_count") or core.get("sockets"),
            "total_cores": cpu_count,
            "cores_per_socket": topology.get("cores_per_socket") or core.get("cores_per_socket"),
            "threads_per_core": topology.get("threads_per_core") or core.get("threads_per_core"),
            "numa_nodes": int(topology.get("numa_node_count") or 1),
            "cores_per_die": cpu_count,
        }
    )
    mhz = str(topology.get("cpu_max_mhz") or "").strip()
    if mhz:
        try:
            core["cpu_clock"] = f"{float(mhz) / 1000.0:.6f}GHz"
        except ValueError:
            pass
    payload["core"] = core

    memory = dict(payload.get("memory", {}))
    memory["numa_nodes"] = int(topology.get("numa_node_count") or 1)
    payload["memory"] = memory

    cross = dict(payload.get("host_cross_check", {}))
    cross.update(
        {
            "auto_generated": True,
            "topology_source": "calibrator/machine_topology.py",
            "template_path": str(template_path),
            "target_numa_node_index": int(numa_node),
            "target_numa_core_count": cpu_count,
            "target_numa_mem_mb": node.get("mem_mb"),
            "lscpu_architecture": topology.get("architecture"),
            "lscpu_vendor": topology.get("vendor_id"),
            "lscpu_model_name": topology.get("model_name"),
            "lscpu_sockets": topology.get("socket_count"),
            "lscpu_cores_per_socket": topology.get("cores_per_socket"),
            "lscpu_threads_per_core": topology.get("threads_per_core"),
            "lscpu_numa_nodes": topology.get("numa_node_count"),
            "lscpu_total_cores": topology.get("logical_cpu_count"),
        }
    )
    payload["host_cross_check"] = cross
    return payload, topology


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Generate a single-NUMA hardware YAML from local topology.")
    parser.add_argument("--template", type=Path, default=DEFAULT_TEMPLATE)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--profile-name", default="")
    parser.add_argument("--numa-node", type=int, default=0)
    parser.add_argument("--topology-json", type=Path)
    return parser.parse_args()


def main() -> int:
    args = _parse_args()
    payload, topology = build_hw_config_from_template(
        template_path=args.template.resolve(),
        profile_name=args.profile_name or None,
        numa_node=int(args.numa_node),
    )
    _dump_yaml_like(args.output.resolve(), payload)
    if args.topology_json:
        write_machine_config(args.topology_json.resolve())
    else:
        sidecar = args.output.resolve().with_suffix(".machine_topology.json")
        sidecar.write_text(json.dumps(topology, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(args.output.resolve())
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
